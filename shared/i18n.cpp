void SetLanguage(Language language) { selected.store(language); }
Language GetLanguage() { return selected.load(); }
void SetSystemLanguageResolver(SystemLanguageResolver resolver) { systemResolver.store(resolver); }
Language EffectiveLanguage() {
    auto language=GetLanguage();if(language!=Language::System)return language;
    auto resolver=systemResolver.load();if(resolver){auto value=resolver();return value==Language::SimplifiedChinese?value:Language::English;}
#ifdef _WIN32
    return PRIMARYLANGID(GetUserDefaultUILanguage())==LANG_CHINESE?Language::SimplifiedChinese:Language::English;
#else
    return Language::English;
#endif
}
const char* LanguageTag(Language language) { return language==Language::English?"en":language==Language::SimplifiedChinese?"zh-Hans":"system"; }
Language ParseLanguageTag(const std::string& tag) { if(tag=="en"||tag=="en-US"||tag=="english")return Language::English;if(tag=="zh-Hans"||tag=="zh-CN"||tag=="zh"||tag=="zh-Hans-CN")return Language::SimplifiedChinese;return Language::System; }
const char* Text(const char* source) {
    if(!source)return "";
    const bool zh=EffectiveLanguage()==Language::SimplifiedChinese;
    for(const auto& entry:catalog)if(std::strcmp(source,entry.zh)==0||std::strcmp(source,entry.en)==0)return zh?entry.zh:entry.en;
    return source;
}
const wchar_t* Text(const wchar_t* source) {
    if(!source)return L"";
    const bool zh=EffectiveLanguage()==Language::SimplifiedChinese;
    for(const auto& entry:catalog)if(std::wcscmp(source,entry.wideZh)==0||std::wcscmp(source,entry.wideEn)==0)return zh?entry.wideZh:entry.wideEn;
    return source;
}
std::string Translate(const std::string& source) { return Text(source.c_str()); }
std::wstring Translate(const std::wstring& source) { return Text(source.c_str()); }
